function haversine(a, b) {
  const R = 6371000;
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  const x =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((a.lat * Math.PI) / 180) *
      Math.cos((b.lat * Math.PI) / 180) *
      Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(x));
}

function pointAtDistanceFromEnd(coords, distanceM) {
  let acc = 0;
  for (let i = coords.length - 1; i > 0; i--) {
    acc += haversine(coords[i], coords[i - 1]);
    if (acc >= distanceM) return coords[i];
  }
  return coords[0];
}

function pointAtDistanceFromStart(coords, distanceM) {
  let acc = 0;
  for (let i = 0; i < coords.length - 1; i++) {
    acc += haversine(coords[i], coords[i + 1]);
    if (acc >= distanceM) return coords[i + 1];
  }
  return coords[coords.length - 1];
}

async function route(from, to) {
  const c = `${from.lng},${from.lat};${to.lng},${to.lat}`;
  const res = await fetch(
    `https://router.project-osrm.org/route/v1/driving/${c}?overview=full&geometries=geojson`
  );
  const j = await res.json();
  if (j.code !== "Ok" || !j.routes?.[0]) throw new Error(`OSRM ${from}->${to}: ${j.code}`);
  return j.routes[0].geometry.coordinates.map(([lng, lat]) => ({ lat, lng }));
}

async function entrances(fromName, toName) {
  const fromC = CITIES[fromName];
  const toC = CITIES[toName];
  const coords = await route(fromC, toC);

  let fromEnt = pointAtDistanceFromStart(coords, ENTRANCE_AFTER_SOURCE_M);
  const toEnt = pointAtDistanceFromEnd(coords, ENTRANCE_BEFORE_DEST_M);

  if (toName === "Nouakchott" && (fromName === "Rosso" || fromName === "Aleg")) {
    fromEnt = NOUK_ENTRANCE_ROSSO;
  }
  if (fromName === "Nouakchott" && toName === "Rosso") {
    fromEnt = NOUK_ENTRANCE_ROSSO;
  }
  if (toName === "Nouakchott" && fromName === "Rosso") {
    return {
      fromEnt: pointAtDistanceFromEnd(coords, ENTRANCE_BEFORE_DEST_M),
      toEnt: NOUK_ENTRANCE_ROSSO,
    };
  }
  if (fromName === "Arafat" && toName === "Tevragh Zeina") {
    return { fromEnt: CITIES.Arafat, toEnt: CITIES["Tevragh Zeina"] };
  }
  if (fromName === "Nouakchott" && toName === "Tevragh Zeina") {
    return {
      fromEnt: NOUK_ENTRANCE_ROSSO,
      toEnt: CITIES["Tevragh Zeina"],
    };
  }

  return { fromEnt, toEnt };
}

function sqlEscape(s) {
  return s.replace(/'/g, "''");
}

